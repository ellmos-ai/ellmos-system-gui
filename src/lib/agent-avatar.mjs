export function avatarVisual(value, identity={}) {
  if (decodeDataUrl(value)) {
    const presetId = selectedDataUrls.get(value);
    const preset = PORTABLE_AVATAR_PRESETS.find(item => item.id === presetId);
    if (preset) return {kind:'preset',id:preset.id,name:preset.name,asset:true,position:null};
    return {kind:'upload',url:value};
  }
  const fallback = 'preset:' + (DEFAULTS[identity.id] || DEFAULTS[identity.role_id || identity.persona_role] || 'companion');
  const preset = AVATAR_PRESETS.find(item=>item.id===value) || AVATAR_PRESETS.find(item=>item.id===fallback);
  return {kind:'preset',id:preset.id,name:preset.name,asset:!('x' in preset),position:('x' in preset)?(preset.x*50)+'% '+(preset.y*100)+'%':null};
}

export function createAvatar(document, value, identity, atlasUrl, className='') {
  const visual=avatarVisual(value,identity);
  const element=document.createElement(visual.kind==='upload'?'img':visual.asset?'img':'span');
  element.className=className;
  element.setAttribute('aria-hidden','true');
  if(visual.kind==='upload') {element.src=visual.url;element.alt='';element.decoding='async';}
  else {
    if (visual.asset) {
      if(typeof atlasUrl!=='string'||!ASSET_URL_RE.test(atlasUrl)) throw new Error('Porträtquelle nicht verfügbar.');
      element.alt='';element.loading='lazy';element.decoding='async';
      element.style.backgroundImage='none';
      element.style.backgroundSize='300% 200%';element.style.backgroundPosition='0% 0%';
      element.style.display='inline-block';
      if(typeof element.addEventListener==='function') element.addEventListener('error',()=>{
        if(typeof element.removeAttribute==='function') element.removeAttribute('src');
        element.dataset.avatarLoadError='true';
        element.style.backgroundImage=`url("${atlasUrl}")`;
      },{once:true});
      const variant=className.includes('avatar-preview')?'large':'thumbnail';
      queueAvatar(element,visual.id,atlasUrl,variant);return element;
    }
    if(typeof atlasUrl!=='string'||!ASSET_URL_RE.test(atlasUrl)) throw new Error('Porträtquelle nicht verfügbar.');
    element.dataset.avatarPreset=visual.id;
    element.style.backgroundImage='url("'+atlasUrl+'")';
    element.style.backgroundSize='300% 200%';element.style.backgroundPosition=visual.position;
    element.style.display='inline-block';
  }
  return element;
}

export function mountAvatarPicker(container,value,identity,atlasUrl,onSelect) {
  if(typeof atlasUrl!=='string'||!ASSET_URL_RE.test(atlasUrl)) throw new Error('Porträtquelle nicht verfügbar.');
  avatarPickerDisposers.get(container)?.();
  let selectedId=avatarVisual(value,identity).kind==='preset'?avatarVisual(value,identity).id:null;
  let confirmedSelectedId=selectedId;
  let page=Math.max(0,Math.floor(Math.max(0,AVATAR_PRESETS.findIndex((preset)=>preset.id===selectedId))/PICKER_PAGE_SIZE));
  let statusText='';let generation=0;let selectionGeneration=0;let selectionPending=false;let disposed=false;let pageImages=[];
  const document=container.ownerDocument;
  const dispose=()=>{
    if(disposed)return;
    disposed=true;generation+=1;selectionGeneration+=1;selectionPending=false;
    for(const image of pageImages)unobserveAvatar(image);
    pageImages=[];
    if(avatarPickerDisposers.get(container)===dispose)avatarPickerDisposers.delete(container);
  };
  avatarPickerDisposers.set(container,dispose);
  const render=()=>{
    if(disposed)return;
    generation+=1;
    for(const image of pageImages)unobserveAvatar(image);
    pageImages=[];
    const grid=document.createElement('div');grid.className='avatar-preset-grid';
    const start=page*PICKER_PAGE_SIZE;const presets=AVATAR_PRESETS.slice(start,start+PICKER_PAGE_SIZE);
    for(const preset of presets){
      const button=document.createElement('button');button.type='button';
      button.className='avatar-preset-choice';button.dataset.preset=preset.id;button.title=preset.name;
      button.setAttribute('aria-label',preset.name);
      button.setAttribute('aria-pressed',String(selectedId===preset.id));
      const image=createAvatar(document,preset.id,identity,atlasUrl,'avatar-preset-image');
      if(image.dataset.avatarVariant)pageImages.push(image);
      button.append(image);
      const name=document.createElement('span');name.textContent=preset.name;button.append(name);
      button.addEventListener('click',async()=>{
        if(disposed)return;
        const selectionToken=++selectionGeneration;
        selectionPending=true;
        try{
          statusText='';selectedId=preset.id;render();
          const selectedValue=PORTABLE_AVATAR_PRESETS.some((item)=>item.id===preset.id)
            ?await portablePresetDataUrl(preset.id):preset.id;
          if(disposed||selectionToken!==selectionGeneration)return;
          await onSelect(selectedValue);
          if(disposed)return;
          confirmedSelectedId=preset.id;
          if(selectionToken===selectionGeneration)selectionPending=false;
          else if(!selectionPending){selectedId=confirmedSelectedId;render();}
        }catch{
          if(disposed||selectionToken!==selectionGeneration)return;
          selectionPending=false;
          selectedId=confirmedSelectedId;
          statusText='Dieses Bild ist gerade nicht verfügbar. Die bisherige Auswahl bleibt erhalten.';
          render();
        }
      });
      grid.append(button);
    }
    const controls=document.createElement('div');controls.className='avatar-preset-pagination';
    const previous=document.createElement('button');previous.type='button';previous.className='button button-secondary';
    previous.textContent='Zurück';previous.setAttribute('aria-label','Vorherige Avatar-Seite');previous.disabled=page===0;
    previous.addEventListener('click',()=>{if(page>0){page-=1;statusText='';render();}});
    const pageLabel=document.createElement('span');pageLabel.setAttribute('aria-live','polite');
    pageLabel.textContent=`${start+1}–${Math.min(start+PICKER_PAGE_SIZE,AVATAR_PRESETS.length)} von ${AVATAR_PRESETS.length}`;
    const next=document.createElement('button');next.type='button';next.className='button button-secondary';
    next.textContent='Weiter';next.setAttribute('aria-label','Nächste Avatar-Seite');next.disabled=start+PICKER_PAGE_SIZE>=AVATAR_PRESETS.length;
    next.addEventListener('click',()=>{if(start+PICKER_PAGE_SIZE<AVATAR_PRESETS.length){page+=1;statusText='';render();}});
    controls.append(previous,pageLabel,next);
    const status=document.createElement('p');status.className='avatar-preset-status';status.setAttribute('role','status');
    status.textContent=statusText;
    container.replaceChildren(grid,controls,status);
  };
  render();
  if(!selectedId&&decodeDataUrl(value)){
    const initialValue=value;const token=generation;
    void presetIdForDataUrl(value).then((id)=>{
      if(disposed||!id||initialValue!==value||token!==generation)return;
      selectedId=id;confirmedSelectedId=id;page=Math.floor(Math.max(0,AVATAR_PRESETS.findIndex((preset)=>preset.id===id))/PICKER_PAGE_SIZE);render();
    }).catch(()=>{});
  }
  return dispose;
}

