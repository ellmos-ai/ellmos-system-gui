export const AVATAR_PRESETS = [...ATLAS_PRESETS,...GEMINI_AVATAR_PRESETS,...PORTABLE_AVATAR_PRESETS];
const DATA_IMAGE_RE = /^data:image\/(png|jpeg|webp);base64,([A-Za-z0-9+/=]+)$/;
const ASSET_URL_RE = /^\/_astro\/[A-Za-z0-9_-][A-Za-z0-9._-]*\.(png|jpg|jpeg|webp)$/;
const MAX_DATA_URL_LENGTH = 240000;
const PICKER_PAGE_SIZE = 18;
const selectedDataUrls = new Map();
let injectedAssetCatalog = null;
let assetCatalogPromise = null;
let avatarObserver = null;
const avatarPickerDisposers = new WeakMap();

export function setAvatarAssetCatalog(catalog) {
  if (!catalog || typeof catalog !== 'object') throw new TypeError('Avatar-Katalog nicht verfügbar.');
  for (const [id, item] of Object.entries(catalog)) {
    if (!/^preset:[a-z0-9-]+$/.test(id) || !item || !ASSET_URL_RE.test(item.thumbnail) ||
        !ASSET_URL_RE.test(item.large) || (item.dataLoader != null && typeof item.dataLoader !== 'function') ||
        (item.sha256 != null && !/^[0-9a-f]{64}$/.test(item.sha256)) ||
        (item.legacySha256 != null && !/^[0-9a-f]{64}$/.test(item.legacySha256))) {
      throw new Error('Porträtquelle nicht verfügbar.');
    }
  }
  injectedAssetCatalog = Object.freeze({...catalog});
  assetCatalogPromise = Promise.resolve(injectedAssetCatalog);
}

function loadAvatarAssetCatalog() {
  if (injectedAssetCatalog) return Promise.resolve(injectedAssetCatalog);
  if (!assetCatalogPromise) {
    assetCatalogPromise = import('./agent-avatar-catalog.mjs').then(({AVATAR_ASSET_CATALOG}) => AVATAR_ASSET_CATALOG);
  }
  return assetCatalogPromise;
}

function observerForAvatars() {
  if (typeof IntersectionObserver !== 'function') return null;
  if (!avatarObserver) {
    avatarObserver = new IntersectionObserver((entries) => {
      for (const entry of entries) {
        if (!entry.isIntersecting) continue;
        avatarObserver.unobserve(entry.target);
        const {avatarPreset, avatarAtlas, avatarVariant} = entry.target.dataset;
        hydrateAvatar(entry.target, avatarPreset, avatarAtlas, avatarVariant).catch(() => {});
      }
    }, {rootMargin: '128px'});
  }
  return avatarObserver;
}

function hydrateAvatar(element, id, atlasUrl, variant='thumbnail') {
  return loadAvatarAssetCatalog().then((catalog) => {
    if (element.isConnected === false) return;
    const asset = catalog[id];
    const url = asset?.[variant] || asset?.thumbnail;
    if (!ASSET_URL_RE.test(url || '')) throw new Error('Porträtquelle nicht verfügbar.');
    element.src = url;
    element.dataset.avatarLoaded = 'true';
  }).catch((error) => {
    if (element.isConnected === false) return;
    element.dataset.avatarLoadError = 'true';
    if (typeof element.removeAttribute === 'function') element.removeAttribute('src');
    element.style.backgroundImage = `url("${atlasUrl}")`;
  });
}

function queueAvatar(element, id, atlasUrl, variant='thumbnail') {
  element.dataset.avatarPreset = id;
  element.dataset.avatarAtlas = atlasUrl;
  element.dataset.avatarVariant = variant;
  const observer = observerForAvatars();
  if (observer) observer.observe(element);
  else hydrateAvatar(element, id, atlasUrl, variant).catch(() => {});
}

function unobserveAvatar(element) {
  avatarObserver?.unobserve(element);
}

function decodeDataUrl(value) {
  const match = typeof value === 'string' && value.length <= MAX_DATA_URL_LENGTH ? DATA_IMAGE_RE.exec(value) : null;
  if (!match) return null;
  const binary = atob(match[2]);
  const bytes = new Uint8Array(binary.length);
  for (let index = 0; index < binary.length; index += 1) bytes[index] = binary.charCodeAt(index);
  return {mime: `image/${match[1]}`, bytes};
}

async function sha256(bytes) {
  if (!globalThis.crypto?.subtle) throw new Error('Bildprüfung wird nicht unterstützt.');
  const digest = await globalThis.crypto.subtle.digest('SHA-256', bytes);
  return [...new Uint8Array(digest)].map((byte) => byte.toString(16).padStart(2, '0')).join('');
}

async function presetIdForDataUrl(value) {
  const cached = selectedDataUrls.get(value);
  if (cached) return cached;
  const decoded = decodeDataUrl(value);
  if (!decoded) return null;
  const hash = await sha256(decoded.bytes);
  const catalog = await loadAvatarAssetCatalog();
  return Object.entries(catalog).find(([, asset]) => asset.kind === 'portable' &&
    (asset.sha256 === hash || asset.legacySha256 === hash))?.[0] ?? null;
}

async function portablePresetDataUrl(id) {
  const catalog = await loadAvatarAssetCatalog();
  const asset = catalog[id];
  if (!asset || asset.kind !== 'portable' || typeof asset.dataLoader !== 'function' || !asset.sha256) throw new Error('Porträtquelle nicht verfügbar.');
  const dataUrl = await asset.dataLoader();
  const decoded = decodeDataUrl(dataUrl);
  if (!decoded || decoded.mime !== 'image/png') throw new Error('Porträtquelle nicht verfügbar.');
  const bytes = decoded.bytes;
  if (bytes.length > 180000 || await sha256(bytes) !== asset.sha256) throw new Error('Porträtquelle nicht verfügbar.');
  let binary = '';
  for (let offset = 0; offset < bytes.length; offset += 0x8000) {
    binary += String.fromCharCode(...bytes.subarray(offset, offset + 0x8000));
  }
  const value = `data:image/png;base64,${btoa(binary)}`;
  if (value.length > MAX_DATA_URL_LENGTH) throw new Error('Porträtquelle nicht verfügbar.');
  selectedDataUrls.set(value, id);
  return value;
}
